#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CustomLutCandidate {
    FastA,
    FastB,
    PreviewFastV1,
    CleanupStrongV1,
}

pub struct X4Panel<SPI, DC, RST, BUSY>(Ssd1677<SPI, DC, RST, BUSY>);

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PanelRamTarget {
    Black,
    Red,
}

impl<SPI, DC, RST, BUSY> X4Panel<SPI, DC, RST, BUSY>
where
    SPI: SpiDevice<u8>,
    DC: OutputPin,
    RST: OutputPin,
    BUSY: InputPin,
{
    #[must_use]
    pub fn new(spi: SPI, dc: DC, reset: RST, busy: BUSY) -> Self {
        Self(Ssd1677::new(spi, dc, reset, busy, panel_config()))
    }

    pub fn init_bw(&mut self, delay: &mut impl DelayNs) -> DisplayResult<()> {
        self.0.init_with_delay(delay)?;
        Ok(())
    }

    pub fn init_absolute_gray(&mut self, delay: &mut impl DelayNs) -> DisplayResult<()> {
        self.0.init_grayscale_with_delay(delay)?;
        self.0.load_waveform(&waveform(&ABSOLUTE_GRAY_LUT))?;
        Ok(())
    }

    pub async fn init_bw_async(&mut self, delay: &mut impl AsyncDelayNs) -> DisplayResult<()> {
        self.0.init_async(delay).await?;
        Ok(())
    }

    pub async fn init_absolute_gray_async(
        &mut self,
        delay: &mut impl AsyncDelayNs,
    ) -> DisplayResult<()> {
        self.0.init_grayscale_async(delay).await?;
        self.0.load_waveform(&waveform(&ABSOLUTE_GRAY_LUT))?;
        Ok(())
    }

    pub fn load_staged_gray(&mut self) -> DisplayResult<()> {
        self.0.load_waveform(&waveform(&STAGED_GRAY_LUT))?;
        Ok(())
    }

    pub fn deep_sleep(&mut self) -> DisplayResult<()> {
        self.0.deep_sleep()?;
        Ok(())
    }

    pub fn load_custom_lut_candidate(
        &mut self,
        candidate: CustomLutCandidate,
    ) -> DisplayResult<()> {
        self.0
            .load_waveform(&custom_lut_candidate_waveform(candidate))?;
        Ok(())
    }

    pub async fn activate_staged_gray(
        &mut self,
        delay: &mut impl AsyncDelayNs,
    ) -> DisplayResult<()> {
        self.0.activate_staged_grayscale_async(delay).await?;
        Ok(())
    }

    pub async fn activate_staged_gray_observed(
        &mut self,
        delay: &mut impl AsyncDelayNs,
        observer: &mut impl BusyWaitObserver,
    ) -> DisplayResult<()> {
        self.0
            .activate_staged_grayscale_async_observed(delay, observer)
            .await?;
        Ok(())
    }

    pub async fn refresh_observed(
        &mut self,
        mode: RefreshMode,
        delay: &mut impl AsyncDelayNs,
        observer: &mut impl BusyWaitObserver,
    ) -> DisplayResult<()> {
        self.0.refresh_async_observed(mode, delay, observer).await?;
        Ok(())
    }

    pub async fn wait_ready_observed(
        &mut self,
        delay: &mut impl AsyncDelayNs,
        observer: &mut impl BusyWaitObserver,
    ) -> DisplayResult<()> {
        self.0.wait_ready_async_observed(delay, observer).await?;
        Ok(())
    }

    pub fn controller(&mut self) -> &mut Ssd1677<SPI, DC, RST, BUSY> {
        &mut self.0
    }

    pub fn write_prepared_rows(
        &mut self,
        first_row: u16,
        rows: &[u8],
        target: PanelRamTarget,
    ) -> DisplayResult<()> {
        if rows.is_empty() || rows.len() % profile::ROW_BYTES != 0 {
            return Err(DisplayError::InvalidPage);
        }
        let row_count = u16::try_from(rows.len() / profile::ROW_BYTES)
            .map_err(|_| DisplayError::InvalidPage)?;
        if first_row
            .checked_add(row_count)
            .is_none_or(|end| end > profile::PHYSICAL_HEIGHT)
        {
            return Err(DisplayError::InvalidPage);
        }
        self.0
            .set_window(0, first_row, profile::PHYSICAL_WIDTH, row_count)?;
        let mut fill = |row: u16, output: &mut [u8; profile::ROW_BYTES]| {
            let start = usize::from(row) * profile::ROW_BYTES;
            output.copy_from_slice(&rows[start..start + profile::ROW_BYTES]);
        };
        match target {
            PanelRamTarget::Black => self.0.write_frame_rows(row_count, &mut fill)?,
            PanelRamTarget::Red => self.0.write_red_frame_rows(row_count, &mut fill)?,
        }
        Ok(())
    }
}

#[must_use]
pub const fn panel_config() -> PanelConfig {
    PanelConfig {
        width: 800,
        height: 480,
        driver_output: [0xdf, 0x01, 0x02],
        booster_soft_start: [0xae, 0xc7, 0xc3, 0xc0, 0x80],
        temperature_sensor: 0x80,
        bw_border_waveform: 0x01,
        grayscale_border_waveform: 0,
        busy_timeout_ms: 60_000,
    }
}

fn waveform(bytes: &'static [u8; 112]) -> Waveform<'static> {
    Waveform {
        lut: &bytes[..105],
        gate_voltage: bytes[105],
        source_voltage: [bytes[106], bytes[107], bytes[108]],
        vcom_voltage: bytes[109],
    }
}

#[must_use]
pub fn custom_lut_candidate_waveform(candidate: CustomLutCandidate) -> Waveform<'static> {
    match candidate {
        CustomLutCandidate::FastA => waveform(&CUSTOM_LUT_FAST_A),
        CustomLutCandidate::FastB => waveform(&CUSTOM_LUT_FAST_B),
        CustomLutCandidate::PreviewFastV1 => waveform(&CUSTOM_LUT_PREVIEW_FAST_V1),
        CustomLutCandidate::CleanupStrongV1 => waveform(&CUSTOM_LUT_CLEANUP_STRONG_V1),
    }
}

#[cfg(test)]
mod tests {
    use super::{
        custom_lut_candidate_waveform, waveform, CustomLutCandidate, ABSOLUTE_GRAY_LUT,
        CUSTOM_LUT_CLEANUP_STRONG_V1, CUSTOM_LUT_FAST_A, CUSTOM_LUT_FAST_B,
        CUSTOM_LUT_PREVIEW_FAST_V1, STAGED_GRAY_LUT,
    };

    #[test]
    fn verified_waveforms_keep_voltage_tail_outside_lut_bytes() {
        for bytes in [
            &ABSOLUTE_GRAY_LUT,
            &STAGED_GRAY_LUT,
            &CUSTOM_LUT_FAST_A,
            &CUSTOM_LUT_FAST_B,
            &CUSTOM_LUT_PREVIEW_FAST_V1,
            &CUSTOM_LUT_CLEANUP_STRONG_V1,
        ] {
            let waveform = waveform(bytes);
            assert_eq!(waveform.lut.len(), 105);
            assert_eq!(waveform.gate_voltage, 0x17);
            assert_eq!(waveform.source_voltage, [0x41, 0xa8, 0x32]);
            assert_eq!(waveform.vcom_voltage, 0x30);
        }
        assert_eq!(&ABSOLUTE_GRAY_LUT[100..105], &[0x22; 5]);
        assert_eq!(&STAGED_GRAY_LUT[100..105], &[0x8f; 5]);
        assert_eq!(
            &custom_lut_candidate_waveform(CustomLutCandidate::FastA).lut[100..105],
            &[0x6f; 5]
        );
        assert_eq!(
            &custom_lut_candidate_waveform(CustomLutCandidate::FastB).lut[100..105],
            &[0x4f; 5]
        );
        assert_eq!(
            &custom_lut_candidate_waveform(CustomLutCandidate::PreviewFastV1).lut[100..105],
            &[0x7f; 5]
        );
        assert_eq!(
            &custom_lut_candidate_waveform(CustomLutCandidate::CleanupStrongV1).lut[100..105],
            &[0xbf; 5]
        );
    }
}
